package cleanui.ui;

import cleanui.CleanUi;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.Font;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.client.gui.screens.Screen;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.ItemStack;
import org.joml.Matrix3x2fStack;

import java.util.List;

/**
 * Design tokens and shared drawing. Default look: pixel-crisp "fancy tooltip" style (navy
 * surfaces, a cyan frame with corner ornaments, dotted leaders, labeled dividers, badges and
 * angled bars). A theme sets the whole palette and a default style; the style knobs (frame,
 * corners, bars, motion) can then be changed on their own in Settings. Every page draws through
 * these helpers, so a theme restyles all of them. Colors are RGB; alpha is applied per draw.
 */
public final class Theme {
	// the palette: not final, the theme sets them (final ints would be baked into every class)
	public static int PANEL = 0x0C1524;
	public static int ROW = 0x13203A;      // rows, cells, buttons
	public static int ROW_HOVER = 0x1B2C4C;
	public static int SLOT = 0x08101D;     // item slots, bar tracks
	public static int LINE = 0x24395A;     // 1px borders and separators
	public static int ACCENT = 0xFFA62B;   // values, highlights
	public static int FRAME = 0x5ED6EA;    // frame, hover/selection borders
	public static int FRAME_DIM = 0x2C7488; // inner frame, ornaments on dividers
	public static int TITLE = 0x7FE6F5;    // page titles, names
	public static int TEXT = 0xF2F5FA;
	public static int TEXT_MUTED = 0x8796B0;
	/** Panel opacity (Glass is see-through). */
	public static float PANEL_ALPHA = 0.96f;
	/** Drop shadow under text; off for light themes (dark ink), worked out from the panel color. See TextShadowMixin. */
	public static boolean textShadow = true;

	/** How the main window's frame is drawn. */
	public enum FrameStyle { ORNATE, CLEAN, BOLD, NONE }

	// the style knobs (Settings), defaulting to the theme's own
	public static FrameStyle frameStyle = FrameStyle.ORNATE;
	public static boolean rounded, flatBars, motion = true;
	private static Preset preset;

	/**
	 * A theme: full palette plus its default style. Tooltip sprites per theme are generated by
	 * tools/GenSprites.java (keep ids and colors in sync).
	 */
	public record Preset(String id, String name, int panel, int row, int rowHover, int slot, int line, int text, int textMuted,
			int accent, int frame, int frameDim, int title, float panelAlpha, FrameStyle frameStyle, boolean rounded, boolean flatBars) {}

	private static Preset navy(String id, String name, int frame, int frameDim, int title) {
		return new Preset(id, name, 0x0C1524, 0x13203A, 0x1B2C4C, 0x08101D, 0x24395A, 0xF2F5FA, 0x8796B0, 0xFFA62B,
				frame, frameDim, title, 0.96f, FrameStyle.ORNATE, false, false);
	}

	public static final List<Preset> PRESETS = List.of(
			navy("cyan", "Cyan", 0x5ED6EA, 0x2C7488, 0x7FE6F5),
			navy("gold", "Gold", 0xD9A441, 0x7A5A22, 0xF5C46A),
			navy("amethyst", "Amethyst", 0xB98CF5, 0x5E3E8C, 0xD7B8FF),
			navy("emerald", "Emerald", 0x5ED68A, 0x2C7A4E, 0x8AF0AE),
			navy("crimson", "Crimson", 0xF0606A, 0x7E2A33, 0xFF9AA0),
			// minimal: near-black, soft white frame, rounded, flat bars, no ornaments
			new Preset("midnight", "Midnight", 0x0E0F13, 0x17191F, 0x22252D, 0x08090C, 0x2A2D36, 0xECEEF2, 0x80869A, 0xF2C14E,
					0xC9CEDB, 0x4A505E, 0xFFFFFF, 0.97f, FrameStyle.CLEAN, true, true),
			// neon: black with a thick magenta frame and cyan names
			new Preset("neon", "Neon", 0x07060D, 0x110E1C, 0x1C1730, 0x040308, 0x2E2550, 0xF6F2FF, 0x9A8FC0, 0xFFE14D,
					0xFF3FD8, 0x7A1E6A, 0x3FF6FF, 0.97f, FrameStyle.BOLD, false, false),
			// glass: see-through blue-grey, clean rounded frame
			new Preset("glass", "Glass", 0x10202E, 0x1C3446, 0x274660, 0x0A1620, 0x3A5A74, 0xF4FAFF, 0x9DB4C8, 0x7FE0FF,
					0xBFE9FF, 0x4E7A96, 0xE6F7FF, 0.72f, FrameStyle.CLEAN, true, true),
			// parchment: light paper, ink text, brown frame
			new Preset("parchment", "Parchment", 0xE9DCBC, 0xDDCCA4, 0xD2BE92, 0xC9B485, 0xA8916A, 0x2B2116, 0x6E5B40, 0xA8521C,
					0x7A4E26, 0xB08E5E, 0x5A3414, 0.98f, FrameStyle.ORNATE, true, true));

	/** Identity colors; each skill or event takes one by index. */
	// shortcut: fixed set; user-picked colors come with the customization phase.
	private static final int[] COLORS = {
			0xB06CF2, // purple
			0x58A8F5, // blue
			0xF06BBE, // pink
			0xF0584A, // red
			0xFFA62B, // orange
			0x6CD655, // green
			0x4FD6C0, // teal
	};

	public static final int PAD = 8;

	/** Switches the palette (and tooltip style) to the theme with this id; unknown ids fall back to the first. */
	public static void applyPreset(String id) {
		preset = byId(id);
		PANEL = preset.panel();
		ROW = preset.row();
		ROW_HOVER = preset.rowHover();
		SLOT = preset.slot();
		LINE = preset.line();
		TEXT = preset.text();
		TEXT_MUTED = preset.textMuted();
		ACCENT = preset.accent();
		FRAME = preset.frame();
		FRAME_DIM = preset.frameDim();
		TITLE = preset.title();
		PANEL_ALPHA = preset.panelAlpha();
		textShadow = luminance(PANEL) < 0.5f;
	}

	public static Preset byId(String id) {
		return PRESETS.stream().filter(p -> p.id().equals(id)).findFirst().orElse(PRESETS.getFirst());
	}

	/** Sets the style knobs (from Settings / the saved config). */
	public static void applyStyle(String frame, boolean rounded, boolean flatBars, boolean motion) {
		try {
			frameStyle = FrameStyle.valueOf(frame);
		} catch (Exception e) {
			frameStyle = FrameStyle.ORNATE;
		}
		Theme.rounded = rounded;
		Theme.flatBars = flatBars;
		Theme.motion = motion;
	}

	public static Preset preset() {
		if (preset == null) applyPreset(PRESETS.getFirst().id());
		return preset;
	}

	/** Vanilla tooltip style id; maps to sprites tooltip/clean_&lt;preset&gt;_background and _frame. */
	public static Identifier tooltipStyle() {
		return Identifier.fromNamespaceAndPath(CleanUi.ID, "clean_" + preset().id());
	}

	/** Corner ornament (top-left orientation), mirrored into the other corners. */
	private static final String[] ORNAMENT = {
			"XXXX.",
			"X....",
			"X.XX.",
			"X.X..",
			"....."};

	private Theme() {}

	public static int color(int index) {
		return COLORS[Math.floorMod(index, COLORS.length)];
	}

	/** 0 (black) .. 1 (white), perceived brightness. */
	static float luminance(int rgb) {
		return (0.299f * ((rgb >> 16) & 0xFF) + 0.587f * ((rgb >> 8) & 0xFF) + 0.114f * (rgb & 0xFF)) / 255f;
	}

	/** RGB + alpha (0..1) → ARGB. */
	public static int argb(int rgb, float alpha) {
		return Math.round(Math.clamp(alpha, 0f, 1f) * 255) << 24 | (rgb & 0xFFFFFF);
	}

	/** Linear blend of two RGB colors. */
	public static int mix(int from, int to, float t) {
		int r = Math.round(((from >> 16) & 0xFF) + (((to >> 16) & 0xFF) - ((from >> 16) & 0xFF)) * t);
		int g = Math.round(((from >> 8) & 0xFF) + (((to >> 8) & 0xFF) - ((from >> 8) & 0xFF)) * t);
		int b = Math.round((from & 0xFF) + ((to & 0xFF) - (from & 0xFF)) * t);
		return r << 16 | g << 8 | b;
	}

	/** Filled rect with a 1px border; with rounded corners on, its corners are cut 2px round. */
	public static void box(GuiGraphicsExtractor g, int x, int y, int w, int h, int bg, float alpha, int border, float borderAlpha) {
		if (rounded && w >= 8 && h >= 8) {
			int c = argb(bg, alpha);
			g.fill(x + 2, y, x + w - 2, y + 1, c);
			g.fill(x + 1, y + 1, x + w - 1, y + 2, c);
			g.fill(x, y + 2, x + w, y + h - 2, c);
			g.fill(x + 1, y + h - 2, x + w - 1, y + h - 1, c);
			g.fill(x + 2, y + h - 1, x + w - 2, y + h, c);
		} else g.fill(x, y, x + w, y + h, argb(bg, alpha));
		outline(g, x, y, w, h, argb(border, borderAlpha));
	}

	/** Box with the standard line border. */
	public static void box(GuiGraphicsExtractor g, int x, int y, int w, int h, int bg, float alpha) {
		box(g, x, y, w, h, bg, alpha, LINE, alpha);
	}

	private static void outline(GuiGraphicsExtractor g, int x, int y, int w, int h, int argb) {
		if (rounded && w >= 8 && h >= 8) { // 2px round corners: lines stop short, one pixel steps in each corner
			g.fill(x + 2, y, x + w - 2, y + 1, argb);
			g.fill(x + 2, y + h - 1, x + w - 2, y + h, argb);
			g.fill(x, y + 2, x + 1, y + h - 2, argb);
			g.fill(x + w - 1, y + 2, x + w, y + h - 2, argb);
			g.fill(x + 1, y + 1, x + 2, y + 2, argb);
			g.fill(x + w - 2, y + 1, x + w - 1, y + 2, argb);
			g.fill(x + 1, y + h - 2, x + 2, y + h - 1, argb);
			g.fill(x + w - 2, y + h - 2, x + w - 1, y + h - 1, argb);
			return;
		}
		g.fill(x, y, x + w, y + 1, argb);
		g.fill(x, y + h - 1, x + w, y + h, argb);
		g.fill(x, y + 1, x + 1, y + h - 1, argb);
		g.fill(x + w - 1, y + 1, x + w, y + h - 1, argb);
	}

	/**
	 * Top-level panel in the current frame style: ORNATE (frame, dim inner frame, pixel ornaments
	 * in each corner), CLEAN (one line), BOLD (2px frame), NONE (a faint line only).
	 */
	public static void panel(GuiGraphicsExtractor g, int x, int y, int w, int h, float a) {
		switch (frameStyle) {
			case CLEAN -> {
				box(g, x, y, w, h, PANEL, a * PANEL_ALPHA, FRAME, a);
				return;
			}
			case BOLD -> {
				box(g, x, y, w, h, PANEL, a * PANEL_ALPHA, FRAME, a);
				outline(g, x + 1, y + 1, w - 2, h - 2, argb(FRAME, a));
				return;
			}
			case NONE -> {
				box(g, x, y, w, h, PANEL, a * PANEL_ALPHA, LINE, a);
				return;
			}
			case ORNATE -> {}
		}
		box(g, x, y, w, h, PANEL, a * PANEL_ALPHA, FRAME, a);
		outline(g, x + 2, y + 2, w - 4, h - 4, argb(FRAME_DIM, a * 0.55f));
		int c = argb(FRAME, a);
		for (int r = 0; r < ORNAMENT.length; r++)
			for (int col = 0; col < ORNAMENT[r].length(); col++)
				if (ORNAMENT[r].charAt(col) == 'X') {
					int ox = 3 + col, oy = 3 + r;
					g.fill(x + ox, y + oy, x + ox + 1, y + oy + 1, c);
					g.fill(x + w - 1 - ox, y + oy, x + w - ox, y + oy + 1, c);
					g.fill(x + ox, y + h - 1 - oy, x + ox + 1, y + h - oy, c);
					g.fill(x + w - 1 - ox, y + h - 1 - oy, x + w - ox, y + h - oy, c);
				}
	}

	/** Horizontal separator with a small link ornament in the middle (like "—⊂⊃—"). */
	public static void divider(GuiGraphicsExtractor g, int x, int y, int w, float a) {
		int mid = x + w / 2, line = argb(LINE, a), orn = argb(FRAME_DIM, a);
		g.fill(x, y, mid - 6, y + 1, line);
		g.fill(mid + 6, y, x + w, y + 1, line);
		outline(g, mid - 5, y - 1, 10, 3, orn);
	}

	/** Section heading: "——◆ LABEL ◆——" across {@code w}, text centered. */
	public static void divider(GuiGraphicsExtractor g, Font font, String label, int x, int y, int w, float a) {
		int tw = font.width(label), tx = x + (w - tw) / 2, line = argb(LINE, a), orn = argb(FRAME_DIM, a);
		g.fill(x, y + 4, tx - 8, y + 5, line);
		g.fill(tx + tw + 8, y + 4, x + w, y + 5, line);
		diamond(g, tx - 6, y + 4, orn);
		diamond(g, tx + tw + 5, y + 4, orn);
		g.text(font, label, tx, y, argb(TEXT_MUTED, a), true);
	}

	/** 3×3 pixel diamond centered on (cx, cy). */
	private static void diamond(GuiGraphicsExtractor g, int cx, int cy, int argb) {
		g.fill(cx, cy - 1, cx + 1, cy + 2, argb);
		g.fill(cx - 1, cy, cx + 2, cy + 1, argb);
	}

	/** Dotted leader between two pieces of text on a row (like "Mining Speed ······ +3,260"). */
	public static void leader(GuiGraphicsExtractor g, int x1, int x2, int y, float a) {
		int c = argb(LINE, a * 1.4f);
		for (int x = x1; x < x2; x += 3) g.fill(x, y, x + 1, y + 1, c);
	}

	/**
	 * {@code left} at x, {@code right} right-aligned at x + w, dotted leader between.
	 * Drops {@code left} if the two would touch, so rows never overlap.
	 */
	public static void textLeader(GuiGraphicsExtractor g, Font font, String left, int leftRgb,
			String right, int rightRgb, int x, int y, int w, float a) {
		int rw = font.width(right), rx = x + w - rw;
		g.text(font, right, rx, y, argb(rightRgb, a), true);
		if (left == null || font.width(left) + 6 > w - rw) return;
		g.text(font, left, x, y, argb(leftRgb, a), true);
		leader(g, x + font.width(left) + 3, rx - 3, y + 6, a);
	}

	/** Like {@link #textLeader} without the dots. */
	public static void textPair(GuiGraphicsExtractor g, Font font, String left, int leftRgb,
			String right, int rightRgb, int x, int y, int w, float a) {
		int rw = font.width(right);
		g.text(font, right, x + w - rw, y, argb(rightRgb, a), true);
		if (left != null && font.width(left) + 6 <= w - rw) g.text(font, left, x, y, argb(leftRgb, a), true);
	}

	/** Filled level badge like the "IV" boxes: colored box, dark text. Drawn right-aligned at {@code right}; returns its width. */
	public static int badge(GuiGraphicsExtractor g, Font font, String text, int right, int y, int rgb, float a) {
		int w = font.width(text) + 5;
		g.fill(right - w, y, right, y + 10, argb(rgb, a));
		outline(g, right - w, y, w, 10, argb(mix(rgb, 0x000000, 0.35f), a));
		g.text(font, text, right - w + 3, y + 1, argb(0x0C1018, a), false); // dark ink on the bright badge, in every theme
		return w;
	}

	/** Outlined tag like "DRILL": border and text in {@code rgb}. Returns its width. */
	public static int tag(GuiGraphicsExtractor g, Font font, String text, int x, int y, int rgb, float a) {
		int w = font.width(text) + 7;
		box(g, x, y, w, 11, SLOT, a, rgb, a);
		g.text(font, text, x + 4, y + 2, argb(rgb, a), false);
		return w;
	}

	/**
	 * Angled progress bar (pointed ends, like the drill fuel bar), optional text centered in it.
	 * {@code h} should be odd so the points are symmetric.
	 */
	public static void bar(GuiGraphicsExtractor g, Font font, int x, int y, int w, int h, float progress, int rgb, String text, float a) {
		if (flatBars) { // plain box track, fill inside
			box(g, x, y, w, h, SLOT, a, LINE, a);
			int fx = x + 1 + Math.round((w - 2) * Math.clamp(progress, 0f, 1f));
			if (fx > x + 1) g.fill(x + 1, y + 1, Math.min(fx, x + w - 1), y + h - 1, argb(rgb, a));
			if (text != null && font.width(text) <= w - 6)
				g.text(font, text, x + (w - font.width(text)) / 2, y + (h - 8) / 2 + 1, argb(TEXT, a), true);
			return;
		}
		int mid = h / 2, fillTo = x + Math.round(w * Math.clamp(progress, 0f, 1f));
		for (int r = 0; r < h; r++) {
			int inset = Math.abs(r - mid);
			int x1 = x + inset, x2 = x + w - inset;
			boolean edge = r == 0 || r == h - 1;
			g.fill(x1, y + r, x2, y + r + 1, argb(edge ? LINE : SLOT, a));
			if (!edge && fillTo > x1 + 1) g.fill(x1 + 1, y + r, Math.min(fillTo, x2 - 1), y + r + 1, argb(rgb, a));
			if (!edge) { // pointed ends outlined
				g.fill(x1, y + r, x1 + 1, y + r + 1, argb(LINE, a));
				g.fill(x2 - 1, y + r, x2, y + r + 1, argb(LINE, a));
			}
		}
		if (text != null && font.width(text) <= w - h * 2)
			g.text(font, text, x + (w - font.width(text)) / 2, y + (h - 8) / 2 + 1, argb(TEXT, a), true);
	}

	/**
	 * First colour in Hypixel text that isn't plain gray/white: a stat symbol's colour, a pet name's
	 * rarity colour. Reads styles, or legacy "§c" codes when the text carries those. Else body text.
	 */
	public static int colorOf(net.minecraft.network.chat.Component c) {
		for (net.minecraft.network.chat.Component part : c.toFlatList()) {
			net.minecraft.network.chat.TextColor tc = part.getStyle().getColor();
			if (tc == null) continue;
			int v = tc.getValue();
			if (v != 0xAAAAAA && v != 0x555555 && v != 0xFFFFFF) return v;
		}
		String s = c.getString();
		for (int i = s.indexOf('§'); i >= 0 && i + 1 < s.length(); i = s.indexOf('§', i + 1)) {
			net.minecraft.ChatFormatting f = net.minecraft.ChatFormatting.getByCode(s.charAt(i + 1));
			net.minecraft.network.chat.TextColor tc = f != null ? net.minecraft.network.chat.TextColor.fromLegacyFormat(f) : null; // null for bold etc.
			if (tc != null && f != net.minecraft.ChatFormatting.GRAY && f != net.minecraft.ChatFormatting.DARK_GRAY
					&& f != net.minecraft.ChatFormatting.WHITE) return tc.getValue();
		}
		return TEXT;
	}

	/**
	 * Gold text with a bright band sweeping left to right, for maxed things.
	 * Driven by the real clock, so it's the same speed at any FPS.
	 */
	public static void shimmer(GuiGraphicsExtractor g, Font font, String text, int x, int y, float a) {
		if (!motion) { // still gold, no sweep
			g.text(font, text, x, y, argb(0xF0B429, a), true);
			return;
		}
		double t = System.nanoTime() / 1e9;
		int cx = x;
		for (int i = 0; i < text.length(); i++) {
			String c = String.valueOf(text.charAt(i));
			double band = Math.sin(t * 4.0 - i * 0.45); // one wave crest travels along the text
			float glow = (float) Math.max(0, band) * 0.75f;
			g.text(font, c, cx, y, argb(mix(0xE8A317, 0xFFF4C2, glow), a), true);
			cx += font.width(c);
		}
	}

	/** Small right-pointing arrow (▸), 4×7 px. */
	public static void arrow(GuiGraphicsExtractor g, int x, int y, int rgb, float a) {
		for (int i = 0; i < 4; i++) g.fill(x + i, y + i, x + i + 1, y + 7 - i, argb(rgb, a));
	}

	/**
	 * Minecraft item drawn at {@code size} px. Items can't be alpha-faded, so they
	 * pop in with a scale as the screen fades in instead.
	 */
	public static void item(GuiGraphicsExtractor g, ItemStack stack, int x, int y, int size, float a) {
		if (a < 0.3f) return;
		float s = size / 16f * (0.6f + 0.4f * Math.min(1f, (a - 0.3f) / 0.7f));
		Matrix3x2fStack pose = g.pose();
		pose.pushMatrix();
		pose.translate(x + size / 2f, y + size / 2f);
		pose.scale(s, s);
		g.item(stack, -8, -8);
		pose.popMatrix();
	}

	/** Item in a dark slot with a cyan-tinted frame, like the item frame on fancy tooltips. */
	public static void slot(GuiGraphicsExtractor g, ItemStack stack, int x, int y, float itemScale, float a) {
		box(g, x, y, 18, 18, SLOT, a, mix(LINE, FRAME, 0.45f), a);
		int size = Math.round(16 * itemScale);
		item(g, stack, x + 9 - size / 2, y + 9 - size / 2, size, a);
	}

	/** Small muted label, e.g. "Seen 12m ago". */
	public static void label(GuiGraphicsExtractor g, Font font, String text, int x, int y, float a) {
		g.text(font, text, x, y, argb(TEXT_MUTED, a), true);
	}

	/** An item's full tooltip (e.g. Hypixel's lore) in the Clean UI style. */
	public static void itemTooltip(GuiGraphicsExtractor g, ItemStack stack, int mouseX, int mouseY) {
		Minecraft mc = Minecraft.getInstance();
		g.setComponentTooltipForNextFrame(mc.font, Screen.getTooltipFromItem(mc, stack), mouseX, mouseY, tooltipStyle());
	}

	/** {@code text} shortened with "…" so it fits in {@code maxW} px. */
	public static String fit(Font font, String text, int maxW) {
		if (font.width(text) <= maxW) return text;
		String s = text;
		while (!s.isEmpty() && font.width(s + "…") > maxW) s = s.substring(0, s.length() - 1);
		return s.strip() + "…";
	}
}
